"""Generates test/test_rtpjpeg/fixtures.h: synthetic JPEG files covering the
cases the RFC 2435 parser must accept or reject.

Usage: python tools/gen_test_fixtures.py   (requires Pillow)
"""
import io
from pathlib import Path

from PIL import Image

OUT = Path(__file__).resolve().parent.parent / "test" / "test_rtpjpeg" / "fixtures.h"


def gradient(width, height):
    img = Image.new("RGB", (width, height))
    px = img.load()
    for y in range(height):
        for x in range(width):
            px[x, y] = ((x * 7) & 255, (y * 5) & 255, ((x + y) * 3) & 255)
    return img


def encode(img, **opts):
    buf = io.BytesIO()
    img.save(buf, "JPEG", quality=80, **opts)
    return buf.getvalue()


# subsampling: 0 = 4:4:4, 1 = 4:2:2, 2 = 4:2:0 (Pillow convention).
CASES = {
    "kJpeg420": encode(gradient(64, 48), subsampling=2),
    "kJpeg422": encode(gradient(64, 48), subsampling=1),
    "kJpeg444": encode(gradient(64, 48), subsampling=0),
    "kJpeg420Dri": encode(gradient(64, 48), subsampling=2, restart_marker_blocks=2),
    "kJpegProgressive": encode(gradient(64, 48), subsampling=2, progressive=True),
    "kJpegOptimizedHuffman": encode(gradient(64, 48), subsampling=2, optimize=True),
    "kJpegGray": encode(gradient(64, 48).convert("L")),
    "kJpegOddSize": encode(gradient(60, 44), subsampling=2),
}


def c_array(name, data):
    lines = [f"static const uint8_t {name}[{len(data)}] = {{"]
    for i in range(0, len(data), 16):
        chunk = ", ".join(f"0x{b:02x}" for b in data[i:i + 16])
        lines.append(f"    {chunk},")
    lines.append("};")
    return "\n".join(lines)


def main():
    parts = [
        "// Generated by tools/gen_test_fixtures.py - do not edit.",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
    ]
    for name, data in CASES.items():
        parts.append(c_array(name, data))
        parts.append("")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(parts), encoding="ascii", newline="\n")
    print(f"wrote {OUT} ({len(CASES)} fixtures)")


if __name__ == "__main__":
    main()
